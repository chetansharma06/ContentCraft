_CURRENCY_PAIRS = {"USD", "INR"}
_MEASUREMENT_FACTORS = {
    "mm": ("length", 0.001),
    "cm": ("length", 0.01),
    "m": ("length", 1.0),
    "in": ("length", 0.0254),
    "ft": ("length", 0.3048),
    "mg": ("mass", 0.001),
    "g": ("mass", 1.0),
    "kg": ("mass", 1000.0),
    "oz": ("mass", 28.349523125),
    "lb": ("mass", 453.59237),
    "ml": ("volume", 1.0),
    "l": ("volume", 1000.0),
    "fl oz": ("volume", 29.5735295625),
}


def translate(language: str, key: str) -> str:
    """Return a localized label, falling back to English for unknown keys."""
    return _TRANSLATIONS.get(language, _TRANSLATIONS["English"]).get(
        key,
        _TRANSLATIONS["English"].get(key, key),
    )


def convert_currency(amount: float, source: str, target: str, inr_per_usd: float) -> float:
    """Convert USD and INR using a caller-supplied INR-per-USD rate."""
    if source not in _CURRENCY_PAIRS or target not in _CURRENCY_PAIRS:
        raise ValueError("Currency must be USD or INR")
    if source == target:
        return amount
    if inr_per_usd <= 0:
        raise ValueError("Exchange rate must be greater than zero")
    return amount * inr_per_usd if source == "USD" else amount / inr_per_usd


def measurement_units(dimension: str) -> tuple[str, ...]:
    """List supported units for a measurement dimension."""
    return tuple(unit for unit, (unit_dimension, _) in _MEASUREMENT_FACTORS.items() if unit_dimension == dimension)


def convert_measurement(value: float, source: str, target: str) -> float:
    """Convert between supported length, mass, or volume units."""
    if source not in _MEASUREMENT_FACTORS or target not in _MEASUREMENT_FACTORS:
        raise ValueError("Unknown measurement unit")
    source_dimension, source_factor = _MEASUREMENT_FACTORS[source]
    target_dimension, target_factor = _MEASUREMENT_FACTORS[target]
    if source_dimension != target_dimension:
        raise ValueError("Units must measure the same dimension")
    return value * source_factor / target_factor
